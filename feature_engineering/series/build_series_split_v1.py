"""
Phase 4A: chronological 70/15/15 train/validation/test split for
data/features/series_features_v1.parquet. Model-agnostic - reusable by any
later model (Random Forest, XGBoost, ...), not just Logistic Regression.

Split unit is the exact `datetime` group (never split a timestamp group
across partitions - matches the same grouping unit Phase 3's engine itself
respects). Boundaries are chosen as the group boundary closest to the 70%/85%
cumulative-row-count marks.

Writes:
    data/modeling/series_split_v1.csv   (match_id, datetime, split)
    reports/phase4a_split_summary.md

The internal `test` partition is written but MUST remain sealed - Phase 4A
must not compute any metric on it.
"""

import pandas as pd

from _common import ROOT, REPORTS

FEATURES_PATH = ROOT / "data" / "features" / "series_features_v1.parquet"
MODELING_DIR = ROOT / "data" / "modeling"
MODELING_DIR.mkdir(exist_ok=True, parents=True)

TRAIN_FRAC = 0.70
VAL_FRAC = 0.15  # -> test is the remaining ~0.15


def pick_boundary_index(cum_counts, target):
    """Index into cum_counts (aligned with the group list) whose cumulative
    count is closest to `target`. Ties/monotonic search - cum_counts is
    non-decreasing by construction."""
    best_i, best_diff = 0, abs(cum_counts[0] - target)
    for i in range(1, len(cum_counts)):
        diff = abs(cum_counts[i] - target)
        if diff < best_diff:
            best_diff, best_i = diff, i
    return best_i


def main():
    df = pd.read_parquet(FEATURES_PATH, engine="fastparquet")
    df = df.sort_values(["datetime", "match_id"]).reset_index(drop=True)
    total = len(df)

    group_sizes = df.groupby("datetime").size().sort_index()
    datetimes = group_sizes.index.tolist()
    counts = group_sizes.values.tolist()
    cum_counts = []
    running = 0
    for c in counts:
        running += c
        cum_counts.append(running)

    target_train = TRAIN_FRAC * total
    target_val_end = (TRAIN_FRAC + VAL_FRAC) * total

    b1 = pick_boundary_index(cum_counts, target_train)
    # search for the validation-end boundary only among groups after b1
    b2_candidates = cum_counts[b1 + 1:]
    if b2_candidates:
        b2_offset = pick_boundary_index(b2_candidates, target_val_end)
        b2 = b1 + 1 + b2_offset
    else:
        b2 = b1

    split_by_datetime = {}
    for i, dt in enumerate(datetimes):
        if i <= b1:
            split_by_datetime[dt] = "train"
        elif i <= b2:
            split_by_datetime[dt] = "validation"
        else:
            split_by_datetime[dt] = "test"

    df["split"] = df["datetime"].map(split_by_datetime)
    assert df["split"].isna().sum() == 0

    # --- integrity: no datetime group crosses a split boundary ---
    per_dt_splits = df.groupby("datetime")["split"].nunique()
    assert (per_dt_splits == 1).all(), "a datetime group was split across partitions"

    split_out = df[["match_id", "datetime", "split"]].sort_values(["datetime", "match_id"])
    split_out.to_csv(MODELING_DIR / "series_split_v1.csv", index=False, encoding="utf-8")

    counts_by_split = df["split"].value_counts()
    print(f"total rows: {total}")
    print(f"train={counts_by_split.get('train',0)} ({100*counts_by_split.get('train',0)/total:.1f}%), "
          f"validation={counts_by_split.get('validation',0)} ({100*counts_by_split.get('validation',0)/total:.1f}%), "
          f"test={counts_by_split.get('test',0)} ({100*counts_by_split.get('test',0)/total:.1f}%)")

    # ---------------- reports/phase4a_split_summary.md ----------------
    md = []
    md.append("# Phase 4A Split Summary\n")
    md.append("Generated by `feature_engineering/series/build_series_split_v1.py`. Chronological 70/15/15 split of "
              "`data/features/series_features_v1.parquet` (the 9,456-row Phase 3 development feature set). "
              "Split unit is the exact `datetime` group - no group is ever divided across partitions, so the "
              "achieved percentages are the closest practical approximation to 70/15/15, not an exact cut.\n")
    md.append("**The internal `test` partition is written to `data/modeling/series_split_v1.csv` but is SEALED "
              "in Phase 4A - no metric is computed on it below or anywhere in this phase.**\n")

    md.append("## Counts and date ranges\n")
    md.append("| split | n | % | first datetime | last datetime |")
    md.append("|---|---|---|---|---|")
    for s in ["train", "validation", "test"]:
        sub = df[df["split"] == s]
        md.append(f"| {s} | {len(sub)} | {100*len(sub)/total:.1f}% | {sub['datetime'].min()} | {sub['datetime'].max()} |")
    md.append("")

    md.append("## Target distribution (team1_series_win) by split\n")
    md.append("| split | win=1 | win=0 | win=1 % |")
    md.append("|---|---|---|---|")
    for s in ["train", "validation", "test"]:
        sub = df[df["split"] == s]
        w1 = int((sub["team1_series_win"] == 1).sum())
        w0 = int((sub["team1_series_win"] == 0).sum())
        md.append(f"| {s} | {w1} | {w0} | {100*w1/len(sub):.1f}% |")
    md.append("")

    md.append("## Tier distribution by split\n")
    tier_tab = pd.crosstab(df["split"], df["tier"])
    md.append("| split | " + " | ".join(tier_tab.columns) + " |")
    md.append("|---|" + "---|" * len(tier_tab.columns))
    for s in ["train", "validation", "test"]:
        row = tier_tab.loc[s] if s in tier_tab.index else None
        md.append(f"| {s} | " + " | ".join(str(row.get(c, 0)) for c in tier_tab.columns) + " |")
    md.append("")

    md.append("## Best-of distribution by split\n")
    bo_tab = pd.crosstab(df["split"], df["bestOf"])
    md.append("| split | " + " | ".join(f"BO{c}" for c in bo_tab.columns) + " |")
    md.append("|---|" + "---|" * len(bo_tab.columns))
    for s in ["train", "validation", "test"]:
        row = bo_tab.loc[s] if s in bo_tab.index else None
        md.append(f"| {s} | " + " | ".join(str(row.get(c, 0)) for c in bo_tab.columns) + " |")
    md.append("")

    (REPORTS / "phases" / "phase4a_split_summary.md").write_text("\n".join(md), encoding="utf-8")
    print("Wrote data/modeling/series_split_v1.csv")
    print("Wrote reports/phase4a_split_summary.md")


if __name__ == "__main__":
    main()
