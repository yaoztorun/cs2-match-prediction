"""
Orientation / side-bias analysis (Phase 2, item 5).

Investigates why the reconstructed team1 win rate is ~55% overall despite
team1 being defined only by the lower per-match surrogate team_id (Phase 1
finding). Diagnostic only - makes no raw-data changes and proposes, but does
not build, a side-symmetric modelling strategy for later phases.

Writes reports/orientation_analysis.md. Read-only against data/raw/ and
data/interim/series_base.parquet.
"""

import pandas as pd

from _common import INTERIM, REPORTS


def rate(df, group_col):
    g = df.groupby(group_col)["team1_series_win"]
    out = g.agg(n="count", team1_wins="sum")
    out["team1_win_rate_pct"] = (100 * out["team1_wins"] / out["n"]).round(1)
    return out


def main():
    sb = pd.read_parquet(INTERIM / "series_base.parquet", engine="fastparquet")
    sb["year"] = sb["datetime"].dt.year

    overall_n = len(sb)
    overall_wins = int(sb["team1_series_win"].sum())
    overall_pct = round(100 * overall_wins / overall_n, 1)

    by_year = rate(sb, "year")
    by_tier = rate(sb, "tier")
    by_bo = rate(sb, "bestOf")

    top_tournaments = sb["tournament"].value_counts().head(20).index
    by_tournament = rate(sb[sb["tournament"].isin(top_tournaments)], "tournament").sort_values("n", ascending=False)

    # Skill-proxy check: each team's DATASET-WIDE win rate (via canonical name),
    # computed across ALL matches (past and future relative to any given match).
    # This is explicitly a diagnostic, whole-dataset/future-aware statistic -
    # it must never be used as an actual model feature (lookahead bias).
    long = pd.concat([
        sb[["team1_canonical", "team1_series_win"]].rename(columns={"team1_canonical": "team", "team1_series_win": "win"}),
        sb[["team2_canonical", "team1_series_win"]].rename(columns={"team2_canonical": "team"}).assign(
            win=1 - sb["team1_series_win"]),
    ], ignore_index=True)
    team_overall_wr = long.groupby("team")["win"].mean()

    sb["team1_overall_wr"] = sb["team1_canonical"].map(team_overall_wr)
    sb["team2_overall_wr"] = sb["team2_canonical"].map(team_overall_wr)
    comparable = sb.dropna(subset=["team1_overall_wr", "team2_overall_wr"])
    comparable = comparable[comparable["team1_overall_wr"] != comparable["team2_overall_wr"]]
    team1_is_stronger = (comparable["team1_overall_wr"] > comparable["team2_overall_wr"])
    n_comparable = len(comparable)
    pct_team1_stronger = round(100 * team1_is_stronger.mean(), 1)

    # among matches where team1 IS the dataset-wide-stronger side, does team1 win more?
    wr_when_team1_stronger = comparable.loc[team1_is_stronger, "team1_series_win"].mean()
    wr_when_team1_weaker = comparable.loc[~team1_is_stronger, "team1_series_win"].mean()

    md = []
    md.append("# Orientation / Side-Bias Analysis\n")
    md.append("Generated by `data_preparation/orientation_analysis.py` from `data/interim/series_base.parquet` "
              f"({len(sb):,} retained series rows). Diagnostic only - no raw data is changed here.\n")

    md.append(f"## Overall team1 win rate\n\n{overall_wins:,}/{overall_n:,} = **{overall_pct}%** "
              "(close to the Phase 1 audit's 55.1%; the small difference is because `series_base` also excludes "
              "the 116 blank-`bestOf` rows that Phase 1's raw denominator included).\n")
    md.append("Recall (Phase 1): `team1_id < team2_id` holds in 100% of rows - `team1` is *defined* as whichever "
              "side got the numerically lower per-match surrogate id, not a home/away/seed designation. A truly "
              "arbitrary assignment would be expected to produce ~50%, so the ~55% figure calls for an explanation.\n")

    def table(df, name):
        lines = [f"### {name}\n", "| group | n | team1 wins | team1 win % |", "|---|---|---|---|"]
        for idx, row in df.iterrows():
            lines.append(f"| {idx} | {int(row['n'])} | {int(row['team1_wins'])} | {row['team1_win_rate_pct']}% |")
        return "\n".join(lines) + "\n"

    md.append(table(by_year.sort_index(), "By year"))
    md.append(table(by_tier.sort_index(), "By tier"))
    md.append(table(by_bo.sort_index(), "By best-of format"))
    md.append(table(by_tournament, "By tournament (20 highest-volume tournaments)"))

    md.append("## Is the ~55% figure flat across slices?\n")
    yr_range = (by_year["team1_win_rate_pct"].min(), by_year["team1_win_rate_pct"].max())
    tier_range = (by_tier["team1_win_rate_pct"].min(), by_tier["team1_win_rate_pct"].max())
    bo_range = (by_bo["team1_win_rate_pct"].min(), by_bo["team1_win_rate_pct"].max())
    md.append(f"- By year: {yr_range[0]}% to {yr_range[1]}%")
    md.append(f"- By tier: {tier_range[0]}% to {tier_range[1]}%")
    md.append(f"- By best-of: {bo_range[0]}% to {bo_range[1]}%")
    md.append("\nThe rate stays close to ~54-58% in every slice checked, rather than swinging toward 50% in some "
              "subgroups and away from it in others. This flatness establishes that **a persistent orientation "
              "bias exists** - it is not randomly distributed across time, tier, or format. It does **not** by "
              "itself identify the mechanism producing that bias; flatness is consistent with several possible "
              "causes and is only one piece of evidence considered below.\n")

    md.append("## Skill-proxy check (DIAGNOSTIC ONLY - see warning below)\n")
    md.append(f"For each team (by `team_canonical`), its win rate was computed across **the entire dataset** "
              "(all matches, past and future relative to any given match) as a rough skill proxy. Of "
              f"{n_comparable:,} series rows where the two teams' dataset-wide win rates differ, team1 (the "
              f"lower-surrogate-id side) is the dataset-wide stronger side in **{pct_team1_stronger}%** of cases. "
              f"When team1 is the dataset-wide-stronger side its actual win rate in that match is "
              f"{wr_when_team1_stronger:.1%}; when team1 is the weaker side its win rate is {wr_when_team1_weaker:.1%}.\n")
    md.append("> **WARNING - diagnostic only, never a model input.** The `team1_overall_wr`/`team2_overall_wr` "
              "statistic used above is computed over the *entire* dataset, including matches that happen chronologically "
              "*after* the match being evaluated. This is a textbook lookahead/future-aware statistic and would leak "
              "target information if used as a real feature. It exists here purely to diagnose whether id-ordering "
              "correlates with an observable strength proxy - it must **never** be carried into `series_base`, "
              "`map_base`, or any feature-engineering script. Any real \"team strength\" feature must be rebuilt "
              "later using only strictly-prior matches (see `reports/preprocessing_rules.md`).\n")
    md.append(f"Result: team1 is the stronger side in {pct_team1_stronger}% of comparable matches - noticeably above "
              "50%, so **team1 orientation correlates somewhat with this diagnostic historical-strength proxy**. "
              "The correlation is partial, not strong (57.4% vs. an uninformative 50%), and the proxy itself is a "
              "rough, future-aware stand-in for skill, not a validated one - this result should be read as one "
              "data point, not as proof of a mechanism.\n")

    md.append("## Conclusion\n")
    md.append("Taken together, the evidence supports the following, and no more than the following:\n")
    md.append("- **A persistent team1 orientation bias exists** (~55% vs. an expected ~50% under a symmetric "
              "assignment), and it is stable across year, tier, and format rather than isolated to one slice.")
    md.append("- **Team1 orientation correlates somewhat with the diagnostic historical-strength proxy** computed "
              "above (team1 is the proxy-stronger side in 57.4% of comparable matches) - a partial, not strong, "
              "relationship.")
    md.append("- **This pattern is consistent with an upstream ordering effect** - for example, some process "
              "upstream of this dataset (bracket layout, scrape order, id-allocation order, etc.) may list or "
              "register one side before the other in a way that is not purely random. This is a plausible "
              "explanation offered for context, not a demonstrated one.")
    md.append("- **The exact cause cannot be established from this dataset.** There is no column recording how or "
              "why `team_id`s were assigned, no access to the original scrape/bracket process, and no independent "
              "way to test alternative explanations (e.g. a genuine but small skill correlation with registration "
              "timing, versus a pure listing artifact) against each other. This analysis stops at documenting the "
              "bias and one supporting correlation, not at proving its origin. No raw data was changed to "
              "investigate this.\n")

    md.append("## Recommendation for future modelling (not built in this phase)\n")
    md.append("Regardless of the unresolved cause, this orientation signal should be **eliminated from modelling** "
              "rather than left for a model to potentially learn as a spurious `team1`-side prior:\n")
    md.append("- **Difference features**: engineer features as `stat_team1 - stat_team2` (or ratios) rather than "
              "separate `team1_*`/`team2_*` columns, so the model cannot learn a spurious `team1`-side prior.")
    md.append("- **Deterministic train-time side-swapping / mirrored augmentation**: for each training row, "
              "optionally also add the mirrored row (`team1`/`team2` swapped, all difference features negated, "
              "target flipped: `1 - team1_series_win`) so the training distribution is exactly side-balanced.")
    md.append("- Whichever approach is used, it must be applied consistently at both train and inference time, and "
              "documented before any model-selection work begins in a later phase.\n")

    (REPORTS / "phases" / "orientation_analysis.md").write_text("\n".join(md), encoding="utf-8")
    print(f"overall team1 win rate: {overall_wins}/{overall_n} = {overall_pct}%")
    print(f"team1 is dataset-wide-stronger side in {pct_team1_stronger}% of {n_comparable} comparable rows")
    print("Wrote reports/orientation_analysis.md")


if __name__ == "__main__":
    main()
