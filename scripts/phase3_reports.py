def df_to_md(df, index_name=""):
    """Minimal markdown-table renderer (avoids adding a `tabulate` dependency
    just for pandas' to_markdown())."""
    cols = [index_name] + list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        vals = [str(idx)] + [f"{v:.4f}" if isinstance(v, float) else str(v) for v in row]
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)
from build_series_features_v1 import SOURCE, build_stream_rows, FEATURES_DIR, CONFIG_PATH


def main():
    cfg = yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8"))
    model_features = cfg["model_features"]

    features = pd.read_parquet(FEATURES_DIR / "series_features_v1.parquet", engine="fastparquet")
    audit = pd.read_parquet(FEATURES_DIR / "series_team_states_v1.parquet", engine="fastparquet")
    excluded = pd.read_csv(INTERIM / "phase3_identity_excluded_matches.csv")
    policy = pd.read_csv(INTERIM / "team_identity_policy.csv")
    sb = pd.read_parquet(INTERIM / "series_base.parquet", engine="fastparquet")
    em = pd.read_csv(INTERIM / "evaluation_manifest.csv")
    with open(FEATURES_DIR / "series_team_state_v1_full.json", encoding="utf-8") as f:
        full_state = json.load(f)

    merged = sb.merge(em, on="match_id", how="inner")
    dev_pool = merged[merged["evaluation_group"] == "development"]
    dev_rows = build_stream_rows(dev_pool)

    ts_group_sizes = dev_rows.groupby("datetime").size()
    n_multi_groups = int((ts_group_sizes > 1).sum())
    n_matches_in_multi_groups = int(ts_group_sizes[ts_group_sizes > 1].sum())

    # ---------------- phase3_feature_engineering.md ----------------
    md = []
    md.append("# Phase 3 V1 - Series-Level Historical Feature Engineering\n")
    md.append(f"Generated by `scripts/phase3_reports.py`. Engine version `{ENGINE_VERSION}` "
              "(`scripts/feature_engine.py`). No models were trained in this phase.\n")

    md.append("## 1. Architecture: reusable engine vs. dataset-specific orchestration\n")
    md.append("`scripts/feature_engine.py` is dataset-agnostic - it has no concept of \"development\", "
              "\"Cologne\", or Kaggle. It exposes:\n")
    md.append("- `build_features(store, team1, team2, prediction_time, best_of, tier)` - **read-only**, "
              "returns a matchup feature dict using only state strictly before `prediction_time`.")
    md.append("- `update_state(store, team1, team2, winner, ..., update_team1, update_team2, update_elo)` - "
              "mutates the store after a result is known.")
    md.append("- `process_chronological_stream(store, rows)` - the shared two-phase batch driver used by every "
              "orchestration mode, so Mode A/B/C can never diverge in their temporal-safety logic.\n")
    md.append("Three modes are supported by this same engine:\n")
    md.append("- **Mode A (implemented here)**: `scripts/build_series_features_v1.py` - batch-generates "
              "leakage-safe feature rows for every eligible development match.")
    md.append("- **Mode B (implemented here)**: `scripts/build_pre_cologne_snapshot.py` - runs a *fresh* store "
              "through the same full development stream, truncated to strictly before the first Cologne 2026 "
              "match, and saves a frozen snapshot for a future pre-event tournament simulation that never sees "
              "real Cologne results.")
    md.append("- **Mode C (future, not implemented)**: given a saved state (`StateStore.from_json`) and a future "
              "scheduled match, call `build_features()` once to get its pre-match features, hand them to a future "
              "model, and after the real result is known call `update_state()` once and continue. "
              "`tests/test_feature_engine.py::test_batch_vs_single_call_equivalence` proves Mode A's batch path "
              "and this one-match-at-a-time path produce identical feature vectors given identical prior history - "
              "training-time and future inference-time feature logic can never diverge because they are the exact "
              "same function calls.\n")

    md.append("## 2. Match identity\n")
    md.append(f"Every processed match carries `source` (`\"{SOURCE}\"` for the current Kaggle data), "
              "`source_match_id` (the provider's own raw match id - NOT assumed globally unique), and "
              "`canonical_match_uid = f\"{source}:{source_match_id}\"` (globally unique by construction). "
              "A future second data source (e.g. GRID, or manually curated rows) can be namespaced under its own "
              "`source` string and appended to the same stream without id collisions, even if its raw match ids "
              "happen to overlap numerically with Kaggle's.\n")

    md.append("## 3. ELO V1\n")
    md.append(f"Initial rating `{ELO_INITIAL}` for every team. `E_A = 1 / (1 + 10 ** ((R_B - R_A) / 400))`. "
              f"`K = {ELO_K}` (fixed). `R_new = R + K * (S - E)`, `S=1` for the winner, `S=0` for the loser. "
              "Deliberately simple: no tournament-tier weighting, no BO1/BO3/BO5 weighting, no time decay, no "
              "margin-of-victory multiplier, no per-context K-factor. This keeps it interpretable and gives a "
              "transparent baseline strength feature; refinements are explicitly postponed (Section 8).\n")

    md.append("## 4. Beta(2,2) smoothing\n")
    md.append(f"`overall_win_rate_smoothed = (wins + {BETA_PRIOR_ALPHA:.0f}) / (matches + {BETA_PRIOR_ALPHA:.0f} + {BETA_PRIOR_BETA:.0f})` "
              "- returns exactly 0.5 for a team with zero prior matches, and is used identically for the "
              "format-specific win rate (restricted to prior matches with the exact same `bestOf` as the current "
              "match, no bucketing beyond exact equality - so the engine supports any future BO value without "
              "special-casing).\n")

    md.append("## 5. Rolling windows and margin\n")
    md.append("`win_rate_last_5`/`win_rate_last_10` use up to the 5/10 most recent strictly-prior matches (fewer "
              "if less history exists; 0.5 with zero history). The signed series margin is `own_score - "
              "opponent_score` from the team's own perspective for that match (e.g. a 2-0 win is +2, a 1-2 loss is "
              "-1, a BO1 loss is -1) - `avg_series_margin_last_5`/`_last_10` average this over the same windows, "
              "0 with zero history.\n")

    md.append("## 6. Cold-start handling\n")
    md.append("A team with no `TeamState` yet (never seen) gets: `elo_before=1500`, "
              "`overall_win_rate_smoothed=0.5`, `win_rate_last_5=0.5`, `win_rate_last_10=0.5`, "
              "`format_win_rate_smoothed=0.5`, `avg_series_margin_last_5/10=0`, `total_matches_before=0`, "
              "`matches_last_30_days=0`, `days_since_last_match=NaN` (never a sentinel like 999 - a downstream "
              "model must be able to tell \"no history\" apart from \"played recently\"). No future information "
              "is ever used to fill these in.\n")

    md.append("## 7. Timestamp batching (temporal safety)\n")
    md.append(f"Across the {len(dev_rows):,}-row development stream, {n_multi_groups:,} exact-timestamp groups "
              f"contain more than one match ({n_matches_in_multi_groups:,} matches total are affected). For every "
              "such group, `process_chronological_stream` computes features for **every** row in the group before "
              "applying **any** result from that group (see `tests/test_feature_engine.py` for the synthetic "
              "proof) - a match at time t never sees another match's result also timestamped t, and no match ever "
              "sees its own result. Within a group, both feature generation and state-update order use a "
              "deterministic secondary sort (`canonical_match_uid`) so a full rerun is byte-identical; true "
              "simultaneity between two matches sharing a team is inherently ambiguous, and applying updates in a "
              "fixed deterministic order is the documented, defensible choice made here rather than attempting to "
              "infer a \"real\" order that the data doesn't record.\n")

    md.append("## 8. Team identity policy\n")
    n_elig = int(policy["identity_feature_eligible"].sum())
    n_inelig = len(policy) - n_elig
    md.append(f"`data/interim/team_identity_policy.csv` mechanically applies the Phase 2.5 proposed decisions "
              f"(no new manual judgments made here): {n_elig}/{len(policy)} original team names are "
              f"`identity_feature_eligible=1` ({n_inelig} are not - 11 `MANUAL_REVIEW` + 3 "
              "`EXCLUDE_FROM_IDENTITY_DEPENDENT_FEATURES`, 0 `NEEDS_EPISODE_SPLIT`). A canonical name is eligible "
              "only if every original spelling mapping to it is eligible (conservative; only relevant to the "
              "`Magic`/`magic` merge today, both eligible, so no real conflict exists yet).\n")
    md.append(f"Of the {len(dev_rows):,} development matches, **{len(excluded):,}** have at least one "
              f"identity-ineligible side and are **excluded from V1 feature rows** "
              "(`data/interim/phase3_identity_excluded_matches.csv`). Refined per the addendum: this does *not* "
              "mean those matches are entirely thrown away. **ELO is the only pair-dependent state component** - "
              "it requires trusting both ratings symmetrically, so it is skipped whenever either side is "
              "ineligible. The *eligible* side's independent state (win/loss record, rolling form, format record, "
              "margin history, activity/experience) still updates from such a match, since that side's own result "
              "is a real, trustworthy fact regardless of the opponent's identity status - the new `HistoryEntry` "
              "is just flagged `opponent_identity_trusted=False` so a future H2H/opponent-dependent feature can "
              "exclude it. The *ineligible* side never has any state tracked at all.\n")

    md.append("## 9. Why only difference features are intended for modelling\n")
    md.append("Phase 1/2 established that `team1`/`team2` are assigned by a per-match numeric-id sort with no "
              "home/away meaning, yet the reconstructed team1 win rate is a persistent ~55% (Phase 2.5's "
              "`orientation_analysis.md`: a real bias, correlated with a diagnostic strength proxy, consistent "
              "with an upstream ordering artifact, exact cause not established). Representing the matchup via "
              "`Team1 - Team2` difference features (plus side-symmetric confidence features) prevents a model "
              "from learning that spurious ordering signal instead of real relative strength. No mirrored "
              "augmentation or side-swapping is implemented in Phase 3 - only the *diff-feature representation* "
              "itself, which is a necessary but not sufficient step; train-time side balancing is deferred to the "
              "modelling phase (Section 11 documents the symmetry invariant this relies on).\n")

    md.append("## 10. Why Cologne is absent\n")
    md.append("`series_features_v1.parquet` is built exclusively from `evaluation_group == \"development\"` "
              "matches. Cologne 2026 and post-Cologne matches are never fed into `process_chronological_stream` "
              "for Mode A, and Mode B's frozen snapshot is further restricted to strictly before Cologne's first "
              "match (derived from `evaluation_manifest.csv`'s `cologne_2026` labels, not from the tournament name "
              "string, which is used only as a secondary sanity cross-check) - `scripts/validate_phase3.py` "
              "checks both independently.\n")

    md.append("## 11. Orientation-symmetry invariant (documented, not a data transform)\n")
    md.append("Given the *same* store state, swapping which team is passed as `team1` vs `team2` to "
              "`build_features` must (a) exactly negate every `*_diff` feature, (b) leave every symmetric "
              "confidence feature unchanged, and (c) would flip the target `1 - team1_series_win` if it were a "
              "real match result. `tests/test_feature_engine.py::test_side_symmetry_of_diff_and_confidence_features` "
              "proves (a)/(b) on synthetic state; (c) is a trivial arithmetic fact checked separately.\n")

    md.append("## 12. Evaluation model vs. future deployment model\n")
    md.append("- **Evaluation model** (Phase 4+, not built yet): trained and backtested strictly without Cologne, "
              "so Cologne stays a genuine, never-touched holdout for judging the approach.")
    md.append("- **Future deployment model** (later, not built yet): once an architecture/hyperparameter choice "
              "has been evaluated and permanently recorded, a separate deployment model may be retrained on *all* "
              "legitimately available historical data at that time, including Cologne and anything completed "
              "after it. The Cologne holdout restriction applies to model development and historical evaluation, "
              "not to the eventual deployed model - this prevents permanently discarding useful historical data "
              "once evaluation is complete.\n")

    md.append("## 13. Canonical match schema (minimum fields for a new future result)\n")
    md.append("The engine does not care whether a completed match came from Kaggle or another source. A new "
              "completed result needs at minimum:\n")
    md.append("```\nmatch_id / source_match_id\ndatetime\nteam1_canonical\nteam2_canonical\nbestOf\n"
              "tier/context (if known)\nscore1_match\nscore2_match\n```\n")
    md.append("Orchestration wraps this into the engine's required stream columns "
              f"(`{', '.join(REQUIRED_STREAM_COLUMNS)}`) by adding `source`, deriving `canonical_match_uid`, and "
              "mapping scores/winner - exactly what `build_series_features_v1.build_stream_rows` does for the "
              "current Kaggle rows.\n")

    md.append("## 14. Future-prediction input contract (before a match starts)\n")
    md.append("**Required**: prediction datetime, Team A canonical identity, Team B canonical identity, BO "
              "format. **Optional/context**: tier, tournament. **Never required**: final score, map result, "
              "current-match statistics, or any other post-match information - `build_features` does not accept "
              "or need any of these. This is what makes the eventual prediction system usable before a real match "
              "starts, not just as a historical-backtest tool.\n")

    md.append("## 15. Cold-start future teams\n")
    md.append("An opponent never seen in the training data is handled automatically by the same cold-start "
              "defaults documented in Section 6 - `store.get(name)` simply returns `None` and "
              "`compute_team_features` falls back to the defaults. `both_teams_have_history`/`_5_matches`/"
              "`_10_matches` expose this to a downstream model so it can distinguish a brand-new opponent from an "
              "established one rather than silently treating them the same.\n")

    md.append("## 16. State versioning\n")
    md.append(f"Every saved `StateStore.to_json()` snapshot embeds `engine_version` (currently `{ENGINE_VERSION}`), "
              "`n_matches_processed` (distinct `canonical_match_uid` count), and a caller-supplied `meta` block "
              "(cutoff datetime, source, mode, generation timestamp) - see `series_team_state_v1_full.json` "
              "(Mode A, full development state) and `pre_cologne_team_state_v1_full.json` (Mode B, frozen "
              "pre-Cologne state) for the two snapshots produced in this phase.\n")

    md.append("## 17. Deliberately postponed\n")
    md.append("Map-level features, player-level/roster features, ELO tuning (time decay, margin-of-victory, "
              "tournament-tier weighting, opponent-strength adjustment, per-context K), head-to-head features, "
              "veto/map-pick logic, mirrored/side-swap data augmentation, any Cologne evaluation or model "
              "inspection, and all model training/hyperparameter tuning. Nothing in this list is implemented or "
              "even prototyped in Phase 3.\n")

    (REPORTS / "phase3_feature_engineering.md").write_text("\n".join(md), encoding="utf-8")

    # ---------------- phase3_feature_quality.md ----------------
    q = []
    q.append("# Phase 3 V1 - Feature Quality Report\n")
    q.append("Generated by `scripts/phase3_reports.py`. **Descriptive only** - none of the numbers below are used "
             "to select, drop, or re-weight any feature in this phase.\n")

    q.append("## Row counts\n")
    q.append(f"- Development matches available (series_base retained rows labeled `development`): {len(dev_rows):,}")
    q.append(f"- Removed for identity uncertainty (>=1 side not `identity_feature_eligible`): {len(excluded):,}")
    q.append(f"- Final `series_features_v1.parquet` row count: {len(features):,}")
    q.append(f"- Reconciliation: {len(features):,} + {len(excluded):,} = {len(features) + len(excluded):,} "
             f"(matches development pool: {len(dev_rows) == len(features) + len(excluded)})\n")

    q.append("## Missingness per feature\n")
    q.append("| feature | % missing |\n|---|---|")
    for c in model_features:
        pct = 100 * features[c].isna().mean()
        q.append(f"| {c} | {pct:.2f}% |")
    q.append("")

    q.append("## Cold-start counts\n")
    q.append(f"- Matches where neither team has ANY prior history (`both_teams_have_history==0`): "
             f"{(features['both_teams_have_history'] == 0).sum():,}")
    q.append(f"- Matches where both teams have >=5 prior matches: {(features['both_teams_have_5_matches'] == 1).sum():,}")
    q.append(f"- Matches where both teams have >=10 prior matches: {(features['both_teams_have_10_matches'] == 1).sum():,}\n")

    q.append("## History-length distribution (`history_matches_sum` = team1+team2 prior matches combined)\n")
    desc = features["history_matches_sum"].describe(percentiles=[0.1, 0.25, 0.5, 0.75, 0.9])
    q.append(df_to_md(desc.to_frame("value"), index_name="stat"))
    q.append("")

    q.append("## ELO range (final state after all processed development matches)\n")
    elos = [t["elo"] for t in full_state["teams"].values()]
    elo_s = pd.Series(elos)
    q.append(f"- min={elo_s.min():.1f}, median={elo_s.median():.1f}, max={elo_s.max():.1f}, "
             f"mean={elo_s.mean():.1f}, std={elo_s.std():.1f} (n={len(elo_s)} teams)\n")

    q.append("## Feature min/median/max\n")
    q.append("| feature | min | median | max |\n|---|---|---|---|")
    for c in model_features:
        if pd.api.types.is_numeric_dtype(features[c]):
            s = features[c]
            q.append(f"| {c} | {s.min():.3f} | {s.median():.3f} | {s.max():.3f} |")
        else:
            q.append(f"| {c} | n/a (categorical: {sorted(features[c].unique())}) | | |")
    q.append("")

    q.append("## Feature-feature correlations (descriptive only)\n")
    numeric_feats = [c for c in model_features if pd.api.types.is_numeric_dtype(features[c])]
    corr = features[numeric_feats].corr(numeric_only=True)
    q.append(df_to_md(corr.round(2), index_name="feature"))
    q.append("")

    q.append("## Target balance\n")
    tb = features["team1_series_win"].value_counts()
    q.append(f"- team1_series_win=1: {tb.get(1, 0):,} ({100 * tb.get(1, 0) / len(features):.1f}%)")
    q.append(f"- team1_series_win=0: {tb.get(0, 0):,} ({100 * tb.get(0, 0) / len(features):.1f}%)\n")

    q.append("## Counts by tier\n")
    q.append(df_to_md(features["tier"].value_counts().to_frame("n"), index_name="tier"))
    q.append("")

    q.append("## Counts by best-of\n")
    q.append(df_to_md(features["bestOf"].value_counts().sort_index().to_frame("n"), index_name="bestOf"))
    q.append("")

    q.append("## Same-timestamp batching\n")
    q.append(f"- Exact-timestamp groups with more than one match: {n_multi_groups:,}")
    q.append(f"- Total matches affected by batching (in a multi-match group): {n_matches_in_multi_groups:,} "
             f"out of {len(dev_rows):,} development rows\n")

    (REPORTS / "phase3_feature_quality.md").write_text("\n".join(q), encoding="utf-8")

    print("Wrote reports/phase3_feature_engineering.md")
    print("Wrote reports/phase3_feature_quality.md")


if __name__ == "__main__":
    main()
